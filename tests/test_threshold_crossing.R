test("threshold crossing is inclusive and spans the full hospitalization", {
  result <- summarize_threshold_crossings(c(20, 40, 80), c(0, 40, 80, 100))
  expect_equal(result$n_reached, c(3, 2, 1, 0))
  expect_equal(result$pct_reached, c(100, 66.67, 33.33, 0))
  stopifnot(all(diff(result$n_reached) <= 0))
})

admission <- as.POSIXct("2020-01-01", tz = "UTC")
crossing_encounters <- tibble(hospitalization_id = letters[1:5], admission_dttm = admission)
crossing_scores <- tibble(
  hospitalization_id = c("a", "a", "b", "c", "d", "e"),
  recorded_dttm = admission + c(0, 2, 1, 6, 6.01, 20) * 3600,
  score_value = c(40, 60, 40, 41, 40, 39)
)
test("first crossings use the earliest qualifying score and configured threshold", {
  crossings <- first_threshold_crossings(crossing_scores, crossing_encounters, 40)
  expect_equal(crossings$hospitalization_id, letters[1:4])
  expect_equal(crossings$hours_from_admission, c(0, 1, 6, 6.01))
  higher <- first_threshold_crossings(crossing_scores, crossing_encounters, 50)
  expect_equal(higher$hospitalization_id, "a")
  expect_equal(higher$hours_from_admission, 2)
})
test("hourly and six-hour bins retain boundary crossings and complete empty hours", {
  crossings <- first_threshold_crossings(crossing_scores, crossing_encounters, 40)
  result <- summarize_first_crossings(crossings, 6)
  expect_equal(result$hourly$hour, 0:7)
  expect_equal(result$hourly$n_crossed_this_hour, c(1, 1, 0, 0, 0, 0, 1, 1))
  expect_equal(result$hourly$n_crossed_cumulative, c(1, 2, 2, 2, 2, 2, 3, 4))
  expect_equal(result$binned$hour_bin, c(0, 6, 12))
  expect_equal(result$binned$n_crossed, c(1, 2, 1))
  expect_equal(result$binned$pct_crossed, c(25, 50, 25))
  expect_equal(result$summary$N, 4)
  expect_equal(result$summary$mean_hours, 3.3)
  expect_equal(result$summary$median_hours, 3.5)
})
test("late crossings remain in the denominator", {
  result <- summarize_first_crossings(tibble(hours_from_admission = c(1, 100)), 6)
  expect_equal(result$binned$pct_crossed[result$binned$hour_bin == 6], 50)
  expect_equal(tail(result$hourly$pct_crossed_cumulative, 1), 100)
})
test("zero crossers yield typed empty tables and missing summary statistics", {
  result <- summarize_first_crossings(tibble(hours_from_admission = numeric()), 6)
  expect_equal(nrow(result$hourly), 0)
  expect_equal(nrow(result$binned), 0)
  expect_equal(result$summary$N, 0)
  stopifnot(is.na(result$summary$mean_hours), is.na(result$summary$median_hours))
})

test("threshold publication protects small differences and the Table 1 threshold anchor", {
  scores <- c(rep(20, 20), rep(39, 3), rep(40, 20), rep(80, 20))
  internal <- summarize_threshold_crossings(scores, c(0, 21, 39, 40, 41, 81, 100))
  public <- publish_threshold_crossings(internal, 10, anchor_counts = 40)
  stopifnot(is.na(public$n_reached[public$threshold == 39]))
  expect_equal(public$n_reached[public$threshold == 40], 40)
  counts <- sort(unique(c(0, 63, 40, public$n_reached)), na.last = NA)
  stopifnot(all(diff(counts) >= 10))
})
test("hourly publication cannot recover a small crossing count using totals or cumulative values", {
  internal <- summarize_first_crossings(tibble(hours_from_admission = c(0, rep(1, 20))), 6)
  public <- publish_first_crossings(internal, 6, 10, cohort_total = 40)
  stopifnot(all(is.na(public$hourly$n_crossed_this_hour)))
  stopifnot(all(is.na(public$binned$n_crossed)))
  expect_equal(public$hourly$n_crossed_cumulative, c(NA_real_, 21))
})
test("hourly and six-hour publication use the same cumulative boundary mask", {
  internal <- summarize_first_crossings(tibble(hours_from_admission = c(rep(1, 20), rep(7, 3), rep(13, 20))), 6)
  public <- publish_first_crossings(internal, 6, 10, cohort_total = 63)
  expect_equal(public$binned$n_crossed[public$binned$hour_bin == 6], 20)
  stopifnot(is.na(public$binned$n_crossed[public$binned$hour_bin == 12]))
  stopifnot(is.na(public$binned$n_crossed[public$binned$hour_bin == 18]))
  released <- sort(unique(c(0, public$hourly$n_crossed_cumulative)), na.last = NA)
  stopifnot(all(diff(released) >= 10))
})
test("small or empty cohorts do not publish supported-count statistics", {
  public7 <- publish_threshold_crossings(summarize_threshold_crossings(c(20), c(0, 40)), 10)
  stopifnot(all(is.na(public7$n_total)), all(is.na(public7$pct_reached)))
  public8 <- publish_first_crossings(summarize_first_crossings(tibble(hours_from_admission = c(1, 2)), 6), 6, 10, cohort_total = 40)
  stopifnot(is.na(public8$summary$N), all(is.na(public8$hourly$n_total_crossers)))
})
